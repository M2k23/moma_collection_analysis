    fout.write("Analysis 1: Most Common Decade for Artwork Creation\n")
    fout.write(f"Most common decade: {top_5_decades.index[0]}\n")
    fout.write(f"Percentage of artwork: {top_5_percentages.iloc[0]}%\n\n")

    fout.write("Analysis 2: Five Most Common Nationalities Among Artists\n")
    fout.write(
    f"Most common nationalities: "
    f"{top_5_nationalities.index[0]}, "
    f"{top_5_nationalities.index[1]}, "
    f"{top_5_nationalities.index[2]}, "
    f"{top_5_nationalities.index[3]}, "
    f"{top_5_nationalities.index[4]}\n\n")

    fout.write("Analysis 3: Average Time Between Artwork Creation and Acquisition\n")
    fout.write(f"Average time: {average_difference:.2f} years\n\n")

    fout.write("Analysis 4: Percentage of Male, Female, and Non-Binary Artists\n")
    fout.write(f"Male: {gender_percentage.iloc[0]}%\n")
    fout.write(f"Female: {gender_percentage.iloc[1]}%\n")
    fout.write(f"Non-Binary: {gender_percentage.iloc[2]}%\n\n")

    fout.write("Analysis 5: Oldest Artwork\n")
    fout.write(f"Oldest Artwork: {oldest_artwork['Title']}\n")
    fout.write(f"Creation Year: {oldest_year}\n\n")

    fout.write("Analysis 6: Department with the Highest Number of Artwork\n")
    fout.write(f"Department: {department_analysis.index[0]}\n")
    fout.write(f"Percentage of Artwork: {department_analysis['Percentage'].iloc[0]:.2f}%\n\n")

    fout.write("Higher-Level Analysis 1: Comparing Medium Popularity in the 20th and 21st century\n")
    fout.write(f"Most popular medium in the 20th century: {most_popular_medium.loc['20th century'][1]}\n")
    fout.write(f"Most popular medium in the 21st century: {most_popular_medium.loc['21st century'][1]}\n\n")

    fout.write("Higher-Level Analysis 2: Comparing the Most Common Decades for Artwork Creation and Acquisition\n")
    fout.write(f"Most common decade for artwork creation: {top_5_decades_created.index[0]}\n")
    fout.write(f"Most common decade for artwork acquisition: {top_5_decades_acquired.index[0]}\n\n")