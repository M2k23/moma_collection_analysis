import pandas as pd
import numpy as np

df_moma = pd.read_csv("Midterm_Input_Kavwahirehi_Maryse.csv")
print(df_moma)

# Inspecting the structure of the dataframe
print(df_moma.info)

# Looking at the number of rows and columns
print(df_moma.shape)

# Inspecting each column
print(df_moma.columns.tolist())

# Inspecting the number of missing values in each column
print(df_moma.isna().sum())

# Looking at the number of columns that are duplicates
print(df_moma.duplicated().sum())

# Making a copy of the dataset to clean
df_moma_clean = df_moma.copy()

# Fills all the empty artist cells with Unknown artist
df_moma_clean["Artist"] = df_moma_clean["Artist"].fillna("Unknown artist")
# Checks all the empty cells have been replaced
print((df_moma_clean["Artist"].isna().sum()))

# Replaces empty  mediums with "Not recorded"
df_moma_clean["Medium"] = df_moma_clean["Medium"].fillna("Not recorded")
# Checks that all empty fields have been replaced
print(df_moma_clean["Medium"].isna().sum())

# Counts the occurence of each value of nationality
print(df_moma_clean["Nationality"].value_counts(dropna=False).head(8))
print("")
# Counts the occurence of unique values of Gender
print(df_moma_clean["Gender"].value_counts(dropna=False))

# Replaces missing values with parentheses
df_moma_clean["Nationality"] = df_moma_clean["Nationality"].fillna("()")

# Removes parentheses from beginning and end of each nationality value
df_moma_clean["Nationality"] = df_moma_clean["Nationality"].str.strip("()")

# Replaces missing values with unknown
df_moma_clean["Nationality"] = df_moma_clean["Nationality"].replace(
    ["", "Nationality unknown"], "unknown"
)

# Repeats the same process with Gender
df_moma_clean["Gender"] = df_moma_clean["Gender"].fillna("()")
df_moma_clean["Gender"] = df_moma_clean["Gender"].str.strip("()")

# If the value of gender is not male, female, or non-binary its replaced with unknown
df_moma_clean.loc[ ~df_moma_clean["Gender"].isin(["male", "female", "non-binary"]),"Gender"
] = "unknown"

print(df_moma_clean["Nationality"].value_counts())

print(df_moma_clean["Gender"].value_counts())

# Checks the Title, Artist, Date and Medium columns
subset_cols = ["Title", "Artist", "Date", "Medium"]

# Every row that has a duplicate is marked true the others are marked false
dup_row = df_moma_clean.duplicated(subset=subset_cols, keep=False)

#Counts and prints the number of rows that are duplicates
print(dup_row.sum())

# Displays the first six duplicate rows sorted by the selected columns
print(df_moma_clean.loc[dup_row, subset_cols].sort_values(subset_cols).head(6))

before = len(df_moma_clean)

df_moma_clean = df_moma_clean.drop_duplicates(subset=subset_cols, keep="first")
# Prints the amount of rows before and after removing duplicates
print("before:", before, ", after:", len(df_moma_clean))

# Converts the values under Date Acquired into a date time format and marks values that can't be converted as NaT
df_moma_clean["DateAcquired"] = pd.to_datetime(df_moma_clean["DateAcquired"], errors="coerce")

# Prints the number of dates that are missing
print(df_moma_clean["DateAcquired"].isna().sum(), "missing, out of", len(df_moma_clean))

# Replaces n.d with a missing value
df_moma_clean["Date"] = df_moma_clean["Date"].replace("n.d.", pd.NA)

# Converts the Date column to string and extracts the first four digits
year = df_moma_clean["Date"].astype("string").str.extract(r"(\d{4})")[0]

# Converts extracted years into numeric values if it can't be done its converted to NaN
df_moma_clean["Date"] = pd.to_numeric(year, errors="coerce").astype("Int64")

# Prints amount of missing values in Date column
print(df_moma_clean["Date"].isna().sum())

# Displaying the clean dataset
print((df_moma_clean))

# Saving clean data to a csv file
df_moma_clean.to_csv("Midterm_Cleaned_Kavwahirehi_Maryse.csv", index=False)

# Analysis 1: Which decade does most of the art created belong to

df_created = df_moma_clean.dropna(subset=['Date'])

# Groups artwork by decade and counts them
decade_counts = df_created.groupby((df_created['Date'] // 10) * 10).size()

# Sorts from most to least frequent
decade_counts = decade_counts.sort_values(ascending=False)

# Finds the top 5 decades
top_5_decades = decade_counts.head(5)


# Calculates the percentage of the art work that was created in each of the top 5 decades
top_5_percentages = round(( top_5_decades / len(df_created))*100, 2)


# Combines counts and percentages into one table
decade_analysis = pd.concat(
    [
        top_5_decades.rename('Frequency'),
        top_5_percentages.rename('Percentage')

    ],

    axis = 1
)

print(decade_analysis)

# Analysis 2: The 5 most common nationalities amongst artists

# Excludes unknown nationalities
df_known_nationalities = df_moma_clean[
    df_moma_clean['Nationality'].str.lower() != 'unknown'
]

# Gets the 5 most common nationalities
top_5_nationalities = df_known_nationalities["Nationality"].value_counts().head(5)

# Calculates the percentage of artworks with known nationalties
top_5_nationalities_percentage = round( (top_5_nationalities / len (df_known_nationalities["Nationality"])) * 100, 2)


# Combines frequency and percentages into one table
nationality_analysis = pd.concat(
    [
        top_5_nationalities.rename('Frequency'),
        top_5_nationalities_percentage.rename('Percentage')

    ],

    axis = 1
)

print(nationality_analysis)

# Analysis 3: What is the average difference between the date created and date acquired

# Creates a data set for date and date acquired where missing values are ignored
df_known_dates =  df_moma_clean.copy().dropna(subset=['Date', 'DateAcquired'])

# Extracts the acquisition year
df_known_dates['AcquisitionYear'] = pd.to_datetime(df_known_dates['DateAcquired']).dt.year

# Calculates the difference in years

df_known_dates['YearDifference'] = (
    df_known_dates["AcquisitionYear"] - df_known_dates["Date"]
)

# Calculates the average difference
average_difference = df_known_dates["YearDifference"].mean()

print("Average difference in years:", round(average_difference, 2))

print(df_known_dates.head(5))

# Analysis 4: What is the percentage of male, female, and nonbinary artists

# Counts the artists in each gender category
gender_breakdown = df_moma_clean["Gender"].value_counts()

# Calculates the percentage for each gender
gender_percentage = round(df_moma_clean["Gender"].value_counts(normalize=True) * 100, 2)

# Combines counts and percentages into one table

gender_analysis = pd.concat(
    [
        gender_breakdown.rename('Frequency'),
        gender_percentage.rename('Percentage')
    ],
    axis=1
)

print(gender_analysis)

# Analysis 5: Find the oldest artwork and its creation date

# Finds the earliest creation year
oldest_year = df_moma_clean["Date"].min()

# Saves the name of the artwork
oldest_artwork = df_moma_clean.loc[
    df_moma_clean['Date'] == oldest_year
].iloc[0]

print( "The oldest artwork is", oldest_artwork['Title'], "and was created in the year", oldest_year)

# Analysis 6: Which department holds the most artwork

# Counts the artists in each gender category
department_breakdown = df_moma_clean["Department"].value_counts()

# Calculates the percentage for each gender
department_percentage = round(df_moma_clean["Department"].value_counts(normalize=True) * 100, 2)

department_analysis = pd.concat(
    [
        department_breakdown.rename('Frequency'),
        department_percentage.rename('Percentage')
    ],
    axis=1
)

print(department_analysis)

# Analysis 7: Which medium is most popular in the 21st vs 20th century

# Removes rows with missing creation years
df_date_created =  df_moma_clean.copy().dropna(subset=['Date'])

# Classifies artwork by century
df_date_created["Century"] = np.where(
    df_date_created["Date"] < 2000,
    "20th century",
    "21st century"
)


# Counts the mediums in each century
medium_by_century = (
    df_date_created.groupby("Century")["Medium"]
    .value_counts()
)

# Finds the most common medium in each century
most_popular_medium = medium_by_century.groupby(level=0).idxmax()

print(most_popular_medium)

# Analysis 8: which decade was most of the art acquired in vs which decade was most of the art created


# Creates a data set for date and date acquired where missing values are ignored
df_known_dates =  df_moma_clean.copy().dropna(subset=['Date', 'DateAcquired'])


# Extracts the acquisition year
df_known_dates['AcquisitionYear'] = pd.to_datetime(df_known_dates['DateAcquired']).dt.year


# Creates a decade columns
df_known_dates["CreationDecade"] = (
    (df_known_dates["Date"] // 10) * 10
)

df_known_dates["AcquisitionDecade"] = (
    (df_known_dates["AcquisitionYear"] // 10) * 10
)

# Finds the top five creation decades
top_5_decades_created = (
    df_known_dates["CreationDecade"]
    .value_counts()
    .head(5)
)

# Finds the top five acquisition decades
top_5_decades_acquired = (
    df_known_dates["AcquisitionDecade"]
    .value_counts()
    .head(5)
)

# Displays the results
print("Top five decades when artwork was created:")
print("")
print(top_5_decades_created)
print("")

print("Top five decades when artwork was acquired:")
print("")
print(top_5_decades_acquired)

# Writing analysis into a text file

with open("Midterm_Output_Kavwahirehi_Maryse.txt", "w",
          encoding="utf-8") as fout:

    fout.write("MoMA Artwork Dataset - Analysis Results\n")
    fout.write("=" * 45 + "\n\n")

